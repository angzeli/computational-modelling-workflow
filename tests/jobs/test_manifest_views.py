"""Disposable by-system symlink views (#41 Phase 5): generated from verified jobs, never authoritative."""
import json
import os
from pathlib import Path
from unittest.mock import patch
from uuid import uuid4
import unittest

from cmw.jobs import manifest_annotations, manifest_views, manifests
from cmw.jobs.manifests import ManifestError
from cmw.jobs.store import Store
from tests.jobs.test_catalogue_cli import run_jobs
from tests.jobs.test_manifests import ManifestCase


class ViewTests(ManifestCase):
    def setUp(self):
        super().setUp()
        self.init()
        self.views = self.project / 'views'

    def job(self, system=None):
        directory = Path(manifests.reserve(self.store, self.project)['job_directory'])
        manifests.add_native(self.store, self.project, cwd=directory, argv=['/bin/true'], engine='Command',
                             name='synthetic')
        if system is not None:
            self.annotate(directory.name, system)
        return directory.name

    def annotate(self, job_id, system):
        manifest_annotations.annotate(self.store, self.project, job_id, {'system': system})

    def generate(self, **options):
        return manifest_views.generate(self.store, self.project, **options)

    def outside(self):
        return {str(path): (path.lstat().st_ino, path.lstat().st_size, path.lstat().st_mtime_ns)
                for path in self.project.rglob('*') if path.is_file() and 'views' not in path.parts
                and not path.name.endswith(('-wal', '-shm'))}  # SQLite's transient read-only files.

    def linked(self):
        return {str(path.relative_to(self.views)): os.readlink(path)
                for path in self.views.rglob('*') if path.is_symlink()}

    def test_verified_systems_are_linked_and_a_rebuild_replaces_the_whole_tree(self):
        for system in ('TiO2', 'In2S3/Co3O4', None, 'TiO2', '.hidden'):
            self.job(system)
        before = self.outside()
        result = self.generate()
        self.assertEqual(self.outside(), before)  # Only views/ is written.
        self.assertEqual(self.linked(), {'system/TiO2/J1': '../../../jobs/J1', 'system/TiO2/J4': '../../../jobs/J4',
                                         'system/In2S3%2FCo3O4/J2': '../../../jobs/J2',
                                         'system/%2Ehidden/J5': '../../../jobs/J5'})
        self.assertEqual((self.views / 'system' / 'TiO2' / 'J1').resolve(), self.project / 'jobs' / 'J1')
        self.assertEqual((result['written'], result['links'], result['unannotated'], result['skipped']),
                         (True, 4, 1, []))
        self.assertEqual(json.loads((self.views / manifest_views.MARKER).read_text())['project'], 'demo')
        self.annotate('J1', 'Co3O4')
        self.annotate('J4', 'X')
        preview = self.generate(dry_run=True)
        self.assertEqual((preview['written'], self.linked()['system/TiO2/J4']), (False, '../../../jobs/J4'))
        self.generate()
        self.assertEqual(sorted(self.linked()), ['system/%2Ehidden/J5', 'system/Co3O4/J1',
                                                 'system/In2S3%2FCo3O4/J2', 'system/X/J4'])
        self.assertEqual([path.name for path in self.project.iterdir() if path.name.startswith('.views')], [])
        text = manifest_views.summary_text(self.generate(dry_run=True))
        self.assertIn('would link 4 job(s) under 4 system(s)', text)

    def test_foreign_or_modified_views_and_non_owners_are_refused_without_deleting_anything(self):
        self.job('Si')
        self.views.mkdir()
        (self.views / 'mine.txt').write_text('user file')
        with self.assertRaisesRegex(ManifestError, 'not generated by `cmw jobs views`'):
            self.generate()
        (self.views / 'mine.txt').unlink()
        self.views.rmdir()
        self.generate()
        stray = self.views / 'system' / 'Si' / 'notes.txt'
        stray.write_text('user notes')
        with self.assertRaisesRegex(ManifestError, 'move it out'):
            self.generate()
        self.assertEqual((stray.read_text(), sorted(self.linked())), ('user notes', ['system/Si/J1']))
        stray.unlink()
        moved = self.project / 'views-real'
        os.rename(self.views, moved)
        self.views.symlink_to(moved)
        with self.assertRaisesRegex(ManifestError, 'not a real directory'):
            self.generate()
        stranger = Store(self.base / 'stranger')
        stranger.enroll_queue(uuid4().hex, 'linux:synthetic-only')
        with self.assertRaisesRegex(ManifestError, 'does not own'):
            manifest_views.generate(stranger, self.project)

    def test_folded_name_clashes_long_names_and_unverified_jobs_are_skipped(self):
        self.job('TiO2')
        self.job('tio2')
        self.job('é' * 200)  # 400 bytes in UTF-8.
        broken = self.job('Si')
        job = self.project / 'jobs' / broken / '.cmw-manifest' / 'job.json'
        job.chmod(0o644)
        job.write_bytes(job.read_bytes() + b' ')
        result = self.generate()
        reasons = {item['id']: item['reason'] for item in result['skipped']}
        self.assertEqual((result['systems'], result['integrity']), ([], 'FAILED'))
        self.assertIn('differs only by case', reasons['J1'])
        self.assertIn('differs only by case', reasons['J2'])
        self.assertIn('longer than 255 bytes', reasons['J3'])
        self.assertIn('integrity is failed', reasons['J4'])
        self.assertEqual(self.linked(), {})

    def test_backfilled_jobs_link_absolutely_to_their_wrapper(self):
        wrapper = self.base / 'runs' / 'J27'
        wrapper.mkdir(parents=True)
        self.job()
        checked = {'status': 'VERIFIED', 'jobs': [
            {'id': 'J1', 'status': 'verified', 'annotations': {'system': 'Si'}},
            {'id': 'node-a/project-queue:J27.1', 'status': 'verified', 'annotations': {'system': 'Si'},
             'sidecar': str(wrapper / '.cmw-manifest')}]}
        with patch.object(manifest_views, 'check', return_value=checked):
            self.generate()
        self.assertEqual(self.linked(), {'system/Si/J1': '../../../jobs/J1',
                                         'system/Si/node-a%2Fproject-queue:J27.1': str(wrapper)})

    def test_cli_previews_and_writes(self):
        self.job('Si')
        state = str(self.store.root)
        code, output = run_jobs(['views', '--manifest-project', str(self.project), '--dry-run', '--json'], state)
        self.assertEqual((code, json.loads(output)['written'], self.views.exists()), (0, False, False), output)
        code, output = run_jobs(['views', '--manifest-project', str(self.project)], state)
        self.assertEqual(code, 0, output)
        self.assertIn('linked 1 job(s) under 1 system(s)', output)
        self.views.joinpath('stray').write_text('x')
        self.assertEqual(run_jobs(['views', '--manifest-project', str(self.project)], state)[0], 2)


if __name__ == '__main__':
    unittest.main()
