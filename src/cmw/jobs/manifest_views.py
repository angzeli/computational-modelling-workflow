"""Disposable by-system symlink views of a manifest project (#41 Phase 5).

``<project>/views/system/<system>/<job ID>`` links each verified job whose
manifest annotations name a studied system to its job directory: relative links
into ``jobs/`` for native jobs, absolute links to the wrapper of a backfilled
legacy job. Views are generated only by an explicit command from one pass of the
integrity check, never read back, and never an anchor or authority. A rebuild
replaces the whole tree; it refuses to touch a ``views/`` it did not generate or
one holding anything but the folders and links its marker records.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import stat
import tempfile
import unicodedata

from .manifest_check import check
from .manifest_legacy import QUALIFIED, order_key
from .manifests import SCHEMA_VERSION, ManifestError, _require_owner, load_project

VIEWS = 'views'
MARKER = '.cmw-views.json'
UNSAFE = re.compile(r'[\x00-\x1f\x7f/%]')


def component(text):
    """A reversible single path component: '/', '%' and controls percent-encoded, never hidden."""
    encoded = UNSAFE.sub(lambda match: f'%{ord(match[0]):02X}', text)
    return '%2E' + encoded[1:] if encoded.startswith('.') else encoded


def plan(store, root, *, volume_uuid_of=None):
    """The view entries one integrity-check pass supports, and why any system or job was left out."""
    root, project = load_project(root)
    _require_owner(store, project)
    result = check(store, root, volume_uuid_of=volume_uuid_of)
    systems, skipped, unannotated = {}, [], 0
    for job in result['jobs']:
        if job['status'] == 'reserved':  # An ID without a job yet.
            continue
        system = (job.get('annotations') or {}).get('system')
        if job['status'] != 'verified':  # Its annotations are not accepted, so its system may be unknown.
            skipped.append({'id': job['id'], 'system': system,
                            'reason': f'integrity is {job["status"]}; views link verified jobs only'})
            continue
        if not system:
            unannotated += 1
            continue
        target = (Path(job['sidecar']).parent if QUALIFIED.fullmatch(job['id']) else root / 'jobs' / job['id'])
        systems.setdefault(system, []).append({'id': job['id'], 'name': component(job['id']), 'target': str(target)})
    folded, entries = {}, []
    for system in systems:  # APFS and many volumes fold case and Unicode normalization.
        folded.setdefault(unicodedata.normalize('NFD', component(system)).casefold(), []).append(system)
    for system, jobs in sorted(systems.items()):
        directory = component(system)
        clash = [other for other in folded[unicodedata.normalize('NFD', directory).casefold()] if other != system]
        if clash:
            reason = f'its folder name differs only by case or Unicode form from {", ".join(map(repr, clash))}'
        elif len(directory.encode()) > 255 or any(len(job['name'].encode()) > 255 for job in jobs):
            reason = 'its folder or link name is longer than 255 bytes'
        else:
            entries.append({'system': system, 'directory': directory,
                            'jobs': sorted(jobs, key=lambda job: order_key(job['id']))})
            continue
        skipped.extend({'id': job['id'], 'system': system, 'reason': reason} for job in jobs)
    return root, project, {'project': project['project_key'], 'root': str(root), 'views': str(root / VIEWS),
                           'integrity': result['status'], 'systems': entries, 'skipped': skipped,
                           'unannotated': unannotated}


def _generated(path, project_key):
    """Refuse a views tree unless every entry is one this command recorded in its marker."""
    try:
        marker = json.loads((path / MARKER).read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise ManifestError(f'{path} exists but was not generated by `cmw jobs views` ({exc}); move it aside') from exc
    links = marker.get('links') if isinstance(marker, dict) else None
    if (not isinstance(marker, dict) or (marker.get('schema_version'), marker.get('project')) != (
            SCHEMA_VERSION, project_key) or not isinstance(links, dict)
            or not all(isinstance(key, str) and isinstance(value, str) for key, value in links.items())):
        raise ManifestError(f'{path} was generated for another project or schema; move it aside')
    folders = {str(Path(link).parent) for link in links} | ({'system'} if links else set())
    for directory, names, files in os.walk(path, topdown=False):
        for name in names + files:
            entry = Path(directory) / name
            relative, mode = str(entry.relative_to(path)), entry.lstat().st_mode
            if stat.S_ISLNK(mode):
                ours = links.get(relative) == os.readlink(entry)
            elif stat.S_ISDIR(mode):
                ours = relative in folders
            else:
                ours = relative == MARKER and stat.S_ISREG(mode)
            if not ours:
                raise ManifestError(f'{entry} was not generated by `cmw jobs views`; move it out of {path} first')


def _remove(path):
    """Delete a verified generated tree: links and the marker are unlinked, never followed."""
    for directory, names, files in os.walk(path, topdown=False):
        for name in names + files:
            entry = Path(directory) / name
            if entry.is_symlink() or not entry.is_dir():
                entry.unlink()
            else:
                entry.rmdir()
    path.rmdir()


def generate(store, root, *, dry_run=False, volume_uuid_of=None):
    """Rebuild ``views/`` from the verified jobs (or only report it with ``dry_run``)."""
    root, project, report = plan(store, root, volume_uuid_of=volume_uuid_of)
    views = root / VIEWS
    if os.path.lexists(views):
        if not stat.S_ISDIR(views.lstat().st_mode):
            raise ManifestError(f'{views} is not a real directory; move it aside')
        _generated(views, project['project_key'])
    links = sum(len(entry['jobs']) for entry in report['systems'])
    if dry_run:
        return {**report, 'links': links, 'written': False}
    staging = Path(tempfile.mkdtemp(prefix='.views-', dir=root))  # Same depth as views/, so relative links hold.
    try:
        written = {}  # Every link and its target, so a rebuild deletes nothing it did not write.
        for entry in report['systems']:
            folder = staging / 'system' / entry['directory']
            folder.mkdir(parents=True)
            for job in entry['jobs']:
                target = Path(job['target'])
                if target.is_relative_to(root):
                    target = os.path.relpath(target, views / 'system' / entry['directory'])
                os.symlink(target, folder / job['name'])
                written[f'system/{entry["directory"]}/{job["name"]}'] = str(target)
        (staging / MARKER).write_text(json.dumps({'schema_version': SCHEMA_VERSION, 'project': project['project_key'],
                                                  'generator': 'cmw jobs views', 'links': written}, sort_keys=True)
                                      + '\n', encoding='utf-8')
        if os.path.lexists(views):
            retired = Path(tempfile.mkdtemp(prefix='.views-old-', dir=root))
            os.rename(views, retired / VIEWS)
            try:
                os.rename(staging, views)
            except OSError:
                os.rename(retired / VIEWS, views)  # Put the previous generation back.
                retired.rmdir()
                raise
            _remove(retired)
        else:
            os.rename(staging, views)
    finally:
        if os.path.lexists(staging):
            _remove(staging)
    return {**report, 'links': links, 'written': True}


def summary_text(result):
    verb = 'would link' if not result['written'] else 'linked'
    lines = [f'{result["project"]} views: {verb} {result["links"]} job(s) under {len(result["systems"])} system(s) '
             f'at {result["views"]}/system; integrity {result["integrity"]}; '
             f'{result["unannotated"]} job(s) have no system']
    for entry in result['systems']:
        lines.append(f'  {entry["directory"]}: {", ".join(job["id"] for job in entry["jobs"])}')
    lines.extend(f'  skipped {item["id"]} ({item["system"]!r}): {item["reason"]}' for item in result['skipped'])
    return '\n'.join(lines)
